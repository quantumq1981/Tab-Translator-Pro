/* Deploy-time build (audit 2026-11-18 M4): transpile the app ONCE so the deployed page never downloads
 * Babel from unpkg or transpiles 1.4 MB of source on every launch.
 *
 *   node scripts/build_app.mjs <site dir> <build stamp>
 *
 * Writes <site>/build/{engine.js, app.js, session-store.js, react-shim.js} and stamps
 * window.__TTP_BUILD__ = "<stamp>" into <site>/index.html, which switches the loader to them.
 * Uses the SAME Babel presets as index.html's development path, and @babel/standalone from tests/
 * (pinned to the version index.html loads). The output is deterministic for a given source + stamp. */
import fs from "node:fs";
import path from "node:path";
import vm from "node:vm";
import { createRequire } from "node:module";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const repo = path.resolve(here, "..");
const [site, stamp] = process.argv.slice(2);
if (!site || !stamp || !/^[\w.-]+$/.test(stamp)) { console.error("usage: node scripts/build_app.mjs <site dir> <stamp: letters, digits, . _ ->"); process.exit(2); }

const require = createRequire(path.join(repo, "tests", "package.json"));
const Babel = require("@babel/standalone");
const PRESETS = [["typescript", { allExtensions: true, isTSX: true, onlyRemoveTypeImports: true }], ["react"]];
/* Load-time (perf audit 2026-11-26): the deployed modules carry no comments and no layout whitespace. The sources
 * are heavily documented (≈ 40 % of engine.tsx is comments), and every launch downloaded AND parsed them:
 * engine.js 303 → 177 KB gzipped, app.js 151 → 105 KB. Names and code are untouched (no mangling), so stack
 * traces and the worker RPC (which calls engine exports by name) read exactly as before. A licence comment
 * (/*! … or @license / @preserve) would be kept. */
const KEEP_COMMENT = (c) => /^!|@license|@preserve/.test(c);
const transpile = (src, filename) => Babel.transform(src, { filename, presets: PRESETS, compact: true, comments: false, shouldPrintComment: KEEP_COMMENT }).code;
const read = (f) => fs.readFileSync(path.join(repo, f), "utf8");
const v = `?v=${stamp}`;

export function buildApp() {
  // the React shim: every export of the vendored UMD React, read from the file the page loads
  const g = {}; g.window = g; g.self = g; vm.createContext(g);
  vm.runInContext(read("vendor/react-18.3.1/react.production.min.js"), g);
  const keys = Object.keys(g.React).filter((k) => /^[A-Za-z_$][\w$]*$/.test(k));
  if (!keys.includes("useState") || !keys.includes("createElement")) throw new Error("vendored React looks wrong");
  const shim = "// generated by scripts/build_app.mjs — ESM view of the vendored UMD React (window.React)\n" +
    "const R = window.React;\nexport default R;\n" + keys.map((k) => `export const ${k} = R.${k};`).join("\n") + "\n";

  const engine = transpile(read("engine.tsx"), "engine.tsx");
  let app = read("TabDecoderPro.tsx");
  const n = { engine: 0, store: 0, react: 0 };
  app = app.replace(/from\s*["']\.\/engine\.tsx["']/g, () => (n.engine++, `from "./engine.js${v}"`));
  app = app.replace(/from\s*["']\.\/session-store\.js["']/g, () => (n.store++, `from "./session-store.js${v}"`));
  app = app.replace(/from\s*["']react["']/g, () => (n.react++, `from "./react-shim.js${v}"`));
  if (!n.engine || !n.store || !n.react) throw new Error(`import rewrite missed something: ${JSON.stringify(n)}`);
  const appJs = transpile(app, "TabDecoderPro.tsx");
  if (/from\s*["'](?:\.\/engine\.tsx|react|\.\/session-store\.js)["']/.test(appJs)) throw new Error("an unrewritten import survived");
  return { "engine.js": engine, "app.js": appJs, "session-store.js": read("session-store.js"), "react-shim.js": shim };
}

const out = buildApp();
const dir = path.join(site, "build");
fs.mkdirSync(dir, { recursive: true });
for (const [f, src] of Object.entries(out)) fs.writeFileSync(path.join(dir, f), src);
const htmlPath = path.join(site, "index.html");
const html = fs.readFileSync(htmlPath, "utf8");
/* modulepreload (perf audit 2026-11-26): without it the browser finds app.js only when the boot module runs
 * (after React), and engine.js / session-store.js / react-shim.js only after app.js has downloaded — two
 * round trips in series before the largest file starts. Preloading all four starts them with the HTML. The
 * URLs are the exact stamped ones the page imports, so the preloaded copy is the one used. */
const preload = Object.keys(out).map((f) => `<link rel="modulepreload" href="./build/${f}${v}" />`).join("\n  ");
const stamped = html.replace('<script>window.__TTP_BUILD__ = "";</script>', `<script>window.__TTP_BUILD__ = "${stamp}";</script>\n  ${preload}`);
if (stamped === html) throw new Error("index.html has no __TTP_BUILD__ placeholder to stamp");
fs.writeFileSync(htmlPath, stamped);
console.log(`built ${Object.keys(out).map((f) => `build/${f} (${Math.round(out[f].length / 1024)} KB)`).join(", ")}; index.html stamped ${stamp}`);
